// The site's two reference pages, built from the product's own sources: the CLI reference from what
// `vago --help` and each `vago <command> --help` print, and the glossary from CONTEXT.md's terms. Hides how
// the help listing and CONTEXT.md are read, so the capture script and the site's tests share one reading.

import { join } from "node:path";

const repo = join(import.meta.dir, "..", "..");

/** A command as `vago --help` lists it: its one or two words, such as `goal new`, and its summary. */
export type ListedCommand = { name: string; summary: string };

/** A term of CONTEXT.md, written there as it is shown, such as `` `before_all` ``. */
export type GlossaryTerm = { term: string; definition: string; avoid: string };

/** What the `vago` this repo builds prints for `args`. Help always exits 0, so anything else throws. */
export function vagoHelp(args: string[]): string {
	const help = Bun.spawnSync([process.execPath, "src/cli.ts", ...args], {
		cwd: repo,
	});
	if (help.exitCode !== 0)
		throw new Error(
			`vago ${args.join(" ")} exited ${help.exitCode}: ${help.stderr}`,
		);
	return help.stdout.toString().trim();
}

/** Every command `vago --help` lists, in its order. */
export function listedCommands(): ListedCommand[] {
	// The listing's command rows: two spaces, the command's one or two words, padding, its summary.
	const commands = [
		...vagoHelp(["--help"]).matchAll(/^ {2}(\S+(?: \S+)?) {2,}(.+)$/gm),
	].map(([, name, summary]) => ({ name: name ?? "", summary: summary ?? "" }));
	if (commands.length === 0)
		throw new Error("vago --help lists no commands: src/cli.ts");
	return commands;
}

/** Every term under `## Language` in CONTEXT.md, in its order. */
export async function glossaryTerms(): Promise<GlossaryTerm[]> {
	const context = await Bun.file(join(repo, "CONTEXT.md")).text();
	const language = context.split(/^## Language$/m)[1] ?? "";
	const terms = language
		.trim()
		.split(/\n\s*\n/)
		.map((block) => {
			const entry = block.match(/^\*\*(.+)\*\*:\n([\s\S]+?)\n(_Avoid_: .+)$/);
			if (entry === null)
				throw new Error(
					`CONTEXT.md: a term is **Term**:, its definition, then _Avoid_:, not\n${block}`,
				);
			const [, term, definition, avoid] = entry;
			return {
				term: term ?? "",
				definition: definition ?? "",
				avoid: avoid ?? "",
			};
		});
	if (terms.length === 0)
		throw new Error("CONTEXT.md: no terms under ## Language");
	return terms;
}

const generatedNote = (source: string) =>
	`<!-- Generated by \`bun run capture\` in site/ from ${source}. Change the source, not this file. -->`;

/** cli-reference.md: the `vago --help` listing, then a section per command holding its `--help`. */
export function cliReferencePage(): string {
	const sections = listedCommands().map(({ name, summary }) =>
		[
			`## vago ${name}`,
			`${summary}.`,
			`\`\`\`text\n${vagoHelp([...name.split(" "), "--help"])}\n\`\`\``,
		].join("\n\n"),
	);
	return [
		"---",
		"title: CLI reference",
		"description: Every vago command with its arguments, flags and an example, as its --help prints them.",
		"order: 90",
		"---",
		"",
		generatedNote("`vago <command> --help`"),
		"",
		"Each command below is what `vago <command> --help` prints. `vago --help` lists them all:",
		"",
		`\`\`\`text\n${vagoHelp(["--help"])}\n\`\`\``,
		"",
		`${sections.join("\n\n")}\n`,
	].join("\n");
}

/** glossary.md: a section per CONTEXT.md term, whose heading links it by name. */
export async function glossaryPage(): Promise<string> {
	const entries = (await glossaryTerms()).map(
		({ term, definition, avoid }) => `## ${term}\n\n${definition}\n\n${avoid}`,
	);
	return [
		"---",
		"title: Glossary",
		"description: The words Vago's code, docs and TUI use, each with what it means and the words it replaces.",
		"order: 91",
		"---",
		"",
		generatedNote("CONTEXT.md"),
		"",
		"Vago's code, docs and TUI use these words exactly as defined here. Each term links by its name, such as `/docs/glossary/#goal-step`, and under _Avoid_ are the words it replaces.",
		"",
		`${entries.join("\n\n")}\n`,
	].join("\n");
}
